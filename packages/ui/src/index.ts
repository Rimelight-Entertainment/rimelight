import type { AstroIntegration } from "astro"
import UnoCSS from "unocss/astro"
import type { UserConfig } from "unocss"
import type { RimelightIcons } from "./icons/defaults"
import rimelightUiPreset, { colorScales, colorNames, getAllColorNames } from "./presets/index"
import { defineTheme, uiConfig } from "./utils/resolver"

export type Theme = "light" | "dark"
export type ThemeColor = keyof typeof colorScales | (string & {})

export interface UIConfig {
  /**
   * Whether to strip default theme classes from all components (bringing your own styling).
   */
  unstyled?: boolean
  /**
   * Configuration for keyboard shortcuts.
   */
  shortcuts?: {
    categories?: Record<string, { label: string }>
  }
  /**
   * Configuration for the Logo component variants.
   */
  logos?: Record<
    string,
    | string
    | {
        light?: string
        dark?: string
        color?: string
        white?: string
        black?: string
        [key: string]: string | undefined
      }
  >
  /**
   * Global component configuration overrides.
   */
  components?: {
    /**
     * Global UI overrides applied to all components. Merged with defaults via our custom recursive
     * merge utility (first arg wins). Values follow the css-variants theme override format.
     */
    themes?: Record<
      string,
      {
        slots?: Record<string, string | ((base: string) => string) | undefined>
        [key: string]: unknown
      }
    >
  }
  /**
   * Custom colors. Each color can be:
   *
   * - **Flat format**: `{ "500": "oklch(0.53 0.21 260)", "600": "oklch(0.44 0.19 260)" }` — used as
   *   the base for autogenerated light and dark shades via `color-mix(in oklch, ...)`.
   * - **Mode format**: provide explicit `light` and/or `dark` buckets to control each scheme
   *   independently:
   *
   *   ```ts
   *   { light: { "500": "oklch(0.53 0.21 260)" }, dark: { "500": "oklch(0.623 0.214 259.8)" } }
   *   ```
   */
  colors?: Record<
    string,
    Record<string, string> | { light?: Record<string, string>; dark?: Record<string, string> }
  >
  autogenerateColorModes?: boolean
  /**
   * Global icon overrides mapping icon names to class names (e.g. `i-lucide-x`) or raw SVG strings.
   */
  icons?: RimelightIcons
  /**
   * Configure which built-in UnoCSS presets are enabled/disabled.
   */
  presets?: {
    wind?: boolean
    typography?: boolean
    icons?: boolean
  }
  /**
   * Custom UnoCSS configuration overrides, routed directly down to the UnoCSS instance.
   */
  unocss?: UserConfig
}

const EXT_RE = /\.(vue|svelte|[jt]sx?|mdx?|astro|html)($|\?)/
const UI_PACKAGE_RE = /[\\/](@rimelight\/ui|packages\/ui)[\\/]/

export function ui(o: UIConfig = {}): AstroIntegration[] {
  const { colors = {}, logos = {}, shortcuts = {}, icons = {}, components, unocss = {} } = o
  const { pipeline, ...userContent } = unocss.content ?? {}
  const include = [
    EXT_RE,
    UI_PACKAGE_RE,
    ...(pipeline && Array.isArray(pipeline.include) ? pipeline.include : [])
  ]

  const defineUiConfig = JSON.stringify({
    unstyled: o.unstyled,
    themes: components?.themes ?? {},
    logos,
    colors: getAllColorNames(colors),
    shortcuts,
    icons
  })

  return [
    UnoCSS({
      ...unocss,
      presets: [rimelightUiPreset(o), ...(unocss.presets ?? [])],
      content: {
        ...userContent,
        pipeline: pipeline === false ? false : { ...pipeline, include }
      }
    }),
    {
      name: "@rimelight/ui",
      hooks: {
        "astro:config:setup": ({ updateConfig }) => {
          updateConfig({
            vite: { define: { "import.meta.env.RIMELIGHT_UI_CONFIG": defineUiConfig } }
          })
        }
      }
    }
  ]
}

export { rimelightUiPreset, defineTheme, uiConfig, colorScales, colorNames }
