import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { extractAllMeta } from "../src/meta/extractAll.ts";

// Regenerates src/meta/generated.ts from the component sources. Run via `vp run generate:meta`
// (also run before `build`), and checked by test/meta.test.ts so a stale file fails CI.
const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(uiRoot, "src", "meta", "generated.ts");

export async function generateMetaSource(): Promise<string> {
  const meta = await extractAllMeta(uiRoot);
  const raw = [
    "// Generated by scripts/generate-meta.ts. Do not edit by hand.",
    'import type { ComponentMetaMap } from "./types.ts";',
    "",
    `export const componentMeta: ComponentMetaMap = ${JSON.stringify(meta, null, 2)};`,
    "",
  ].join("\n");

  try {
    return execSync("vp fmt --stdin-filepath=generated.ts", {
      input: raw,
      encoding: "utf8",
      cwd: uiRoot,
    });
  } catch {
    return raw;
  }
}

if (import.meta.main) {
  writeFileSync(outFile, await generateMetaSource());
  console.log(`Wrote ${path.relative(uiRoot, outFile)}`);
}
