const HOMOGLYPH_MAP: Record<string, string> = {
  "0": "o",
  "1": "i",
  "3": "e",
  "4": "a",
  "5": "s",
  "7": "t",
  "8": "b",
  "9": "g",
  "@": "a",
  "!": "i",
  "$": "s",
  "|": "i"
}

export const normalizeUsername = (input: string): string => {
  return input
    .toLowerCase()
    .split("")
    .map((char) => HOMOGLYPH_MAP[char] || char)
    .join("")
    .replace(/[^a-z0-9]/g, "")
}

