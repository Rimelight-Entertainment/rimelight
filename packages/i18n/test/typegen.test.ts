import { describe, expect, it } from "vite-plus/test";
import { collectKeys, renderKeyDeclarations } from "../src/typegen";

const keysOf = (dict: Record<string, unknown>) =>
  Object.fromEntries(collectKeys(dict).map((e) => [e.key, Object.fromEntries(e.params)]));

describe("typed keys generator", () => {
  it("emits leaves, plurals and arrays as keys, and skips plain namespaces", () => {
    const keys = keysOf({
      nav: { home: "Home", about: { title: "About" } },
      items: { one: "{count} item", other: "{count} items" },
      tags: ["a", "b {name}"],
      flags: { featured: true },
    });
    expect(Object.keys(keys).sort()).toEqual([
      "flags.featured",
      "items",
      "nav.about.title",
      "nav.home",
      "tags",
    ]);
    expect(keys["nav.home"]).toEqual({});
    expect(keys["items"]).toEqual({ count: "number" });
    expect(keys["tags"]).toEqual({ name: "string | number" });
  });

  it("types placeholders from every string in the key, including inside plurals", () => {
    const keys = keysOf({
      msg: "Hi {user}, {count} new",
      plural: { one: "{count} by {user}", other: "{count} by {user}s" },
    });
    expect(keys["msg"]).toEqual({ user: "string | number", count: "string | number" });
    expect(keys["plural"]).toEqual({ count: "number", user: "string | number" });
  });

  it("skips unsafe keys", () => {
    const keys = keysOf({ ["__proto__"]: { x: "y" }, ok: "fine" } as Record<string, unknown>);
    expect(Object.keys(keys)).toEqual(["ok"]);
  });

  it("renders a module augmentation with sorted entries", () => {
    const out = renderKeyDeclarations(collectKeys({ zeta: "z {name}", alpha: "a" }));
    expect(out).toBe(
      [
        "// Generated by @rimelight/i18n from the base locale. Do not edit.",
        "export {};",
        "",
        'declare module "@rimelight/i18n" {',
        "  interface TranslationRegistry {",
        "    alpha: never;",
        "    zeta: { name: string | number };",
        "  }",
        "}",
        "",
      ].join("\n"),
    );
  });

  it("renders an empty registry when there are no keys", () => {
    expect(renderKeyDeclarations([])).toContain("interface TranslationRegistry {}");
  });
});
