import fs from "node:fs";
import path from "node:path";
import { placeholderNames, UNSAFE_KEYS } from "./shared";

const PLURAL_CATEGORIES = new Set(["zero", "one", "two", "few", "many", "other"]);
const PARAM_TYPE = "string | number";

/** A key `t()` accepts, with the TypeScript type of each param it needs (empty when it takes none). */
interface KeyEntry {
  key: string;
  params: Map<string, string>;
}

const paramsOf = (value: unknown): Map<string, string> =>
  new Map(placeholderNames(value).map((name) => [name, PARAM_TYPE]));

const isPluralObject = (value: object): boolean => {
  const keys = Object.keys(value);
  return keys.length > 0 && keys.every((k) => PLURAL_CATEGORIES.has(k));
};

/**
 * Every key `t()` should accept: strings, numbers, booleans, arrays and plural containers.
 * Plain namespaces are skipped; reach them with `t.raw`.
 */
export const collectKeys = (
  node: Record<string, unknown>,
  prefix = "",
  out: KeyEntry[] = [],
): KeyEntry[] => {
  for (const [name, value] of Object.entries(node)) {
    if (UNSAFE_KEYS.has(name)) continue;
    const key = prefix ? `${prefix}.${name}` : name;
    if (value && typeof value === "object" && !Array.isArray(value)) {
      if (isPluralObject(value)) {
        out.push({ key, params: paramsOf(value).set("count", "number") });
      } else {
        collectKeys(value as Record<string, unknown>, key, out);
      }
    } else {
      out.push({ key, params: paramsOf(value) });
    }
  }
  return out;
};

/** Bare when it is an identifier, quoted otherwise, matching what the formatter would write. */
const prop = (name: string): string =>
  /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);

const renderParams = (params: Map<string, string>): string =>
  params.size === 0
    ? "never"
    : `{ ${[...params]
        .sort(([a], [b]) => (a < b ? -1 : 1))
        .map(([name, type]) => `${prop(name)}: ${type}`)
        .join("; ")} }`;

/**
 * Module augmentation that types `t()` from the registry. It must stay a module (`export {}`),
 * or `declare module` would replace the package instead of augmenting it.
 */
const renderKeyDeclarations = (entries: KeyEntry[]): string => {
  const sorted = [...entries].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  const members = sorted.map((e) => `    ${prop(e.key)}: ${renderParams(e.params)};\n`);
  return [
    "// Generated by @rimelight/i18n from the base locale. Do not edit.",
    "export {};",
    "",
    'declare module "@rimelight/i18n" {',
    `  interface TranslationRegistry {${members.length ? `\n${members.join("")}  ` : ""}}`,
    "}",
    "",
  ].join("\n");
};

/** Writes the file only when its content changed, so watchers and mtimes stay quiet. */
const writeTypeDeclarations = (targetPath: string, content: string): boolean => {
  if (fs.existsSync(targetPath) && fs.readFileSync(targetPath, "utf-8") === content) return false;
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, content, "utf-8");
  return true;
};

interface SyncKeysOptions {
  root: string;
  /** Locale directory, relative to `root`. */
  dir: string;
  baseLocale: string;
  /** Inline translations; when set, they are used instead of reading `dir`. */
  translations?: Record<string, Record<string, unknown>> | undefined;
  /** Output file, relative to `root`. */
  out: string;
}

export interface SyncKeysResult {
  written: boolean;
  keys: number;
}

/** Regenerates the typed-keys file from the base locale. `undefined` when there is no base locale yet. */
export const syncTypedKeys = ({
  root,
  dir,
  baseLocale,
  translations,
  out,
}: SyncKeysOptions): SyncKeysResult | undefined => {
  const base = translations
    ? translations[baseLocale]
    : readJson(path.resolve(root, dir, `${baseLocale}.json`));
  if (!base) return undefined;
  const entries = collectKeys(base as Record<string, unknown>);
  const written = writeTypeDeclarations(path.resolve(root, out), renderKeyDeclarations(entries));
  return { written, keys: entries.length };
};

const readJson = (file: string): unknown =>
  fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf-8")) : undefined;

/** Every `<locale>.json` in a directory, keyed by locale. Empty when the directory is missing. Throws, naming the file, when one fails to parse. */
export const readLocaleFiles = (dir: string): Record<string, Record<string, any>> => {
  const out: Record<string, Record<string, any>> = {};
  if (!fs.existsSync(dir)) return out;
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    try {
      out[path.basename(file, ".json")] = JSON.parse(
        fs.readFileSync(path.join(dir, file), "utf-8"),
      );
    } catch (error) {
      throw new Error(`Failed to parse ${file}: ${(error as Error).message}`);
    }
  }
  return out;
};
