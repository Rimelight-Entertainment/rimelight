function slintId(segs: string[]): string {
  const id = segs.map((s) => s.toLowerCase().replace(/[^a-z0-9-]+/g, "-")).join("-");
  return /^[0-9]/.test(id) ? `n-${id}` : id;
}

function rustIdent(segs: string[]): string {
  const id = segs
    .map((s) => s.replace(/[^A-Za-z0-9]+/g, "_"))
    .join("_")
    .toUpperCase();
  return /^[0-9]/.test(id) ? `N_${id}` : id;
}

const RUST_KEYWORDS = new Set([
  "type",
  "match",
  "move",
  "ref",
  "box",
  "loop",
  "mod",
  "use",
  "impl",
  "trait",
  "struct",
  "enum",
  "fn",
  "let",
  "mut",
  "static",
  "const",
  "where",
  "async",
  "await",
  "dyn",
  "super",
  "self",
  "crate",
  "extern",
  "union",
  "unsafe",
  "yield",
  "macro",
]);

function rustMod(group: string): string {
  if (group === "type") return "typography";
  const id = group.replace(/[^a-z0-9_]/g, "_");
  return RUST_KEYWORDS.has(id) ? `${id}_` : id;
}

function cssFamily(f: string): string {
  return /\s/.test(f) ? JSON.stringify(f) : f;
}

