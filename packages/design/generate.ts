// Design token generator. Reads tokens.json (DTCG format, see SCHEMA.md) and writes the generated outputs.
//
// Usage:
//   node generate.ts                       write all outputs next to this file
//   node generate.ts --check               compare outputs on disk, exit 1 on any difference or contrast FAIL
//   node generate.ts --source <path>       read another tokens.json
//   node generate.ts --out <dir>           write outputs under another root (same relative layout)

