type Leaf = { kind: string; path: string[]; value: any };

function cssOutput(leaves: Leaf[], ramps: string[], shadeOrder: string[]): string {
  const lines: string[] = [];
  const motion: string[] = [];
  lines.push(`/* ${HEADER} */`);
  lines.push(":root {");
  lines.push("  color-scheme: light dark;");
  for (const l of leaves) {
    const name = `--rl-${l.path.join("-")}`;
    switch (l.kind) {
      case "color":
        lines.push(`  ${name}: light-dark(${hex8(l.value.light)}, ${hex8(l.value.dark)});`);
        break;
      case "px":
        lines.push(`  ${name}: ${fmt(l.value)}px;`);
        break;
      case "ms":
        lines.push(`  ${name}: ${fmt(l.value)}ms;`);
        motion.push(name);
        break;
      case "easing":
        lines.push(`  ${name}: cubic-bezier(${l.value.map(fmt).join(", ")});`);
        break;
      case "font":
        lines.push(`  ${name}: ${l.value.map(cssFamily).join(", ")};`);
        break;
      case "int":
        lines.push(`  ${name}: ${l.value};`);
        break;
      case "shadow": {
        const v = l.value;
        lines.push(
          `  ${name}: ${fmt(v.offsetX)}px ${fmt(v.offsetY)}px ${fmt(v.blur)}px ${fmt(v.spread)}px light-dark(${hex8(v.color.light)}, ${hex8(v.color.dark)});`,
        );
        break;
      }
      default:
        fail(`internal: unknown leaf kind ${l.kind}`);
    }
  }
  for (const p of ramps) {
    for (const s of shadeOrder) lines.push(`  --rl-${p}-${s}: var(--rl-ramp-${p}-${s});`);
  }
  lines.push("}");
  lines.push('[data-theme="light"] { color-scheme: light; }');
  lines.push('[data-theme="dark"] { color-scheme: dark; }');
  if (motion.length > 0) {
    lines.push("@media (prefers-reduced-motion: reduce) {");
    lines.push("  :root {");
    for (const name of motion) lines.push(`    ${name}: 0ms;`);
    lines.push("  }");
    lines.push("}");
  }
  return lines.join("\n") + "\n";
}

function jsonOutput(
  colours: Map<string, Pair>,
  others: Token[],
  fontList: (v: unknown, where: string) => string[],
  sideToRGBA: (side: unknown, theme: (typeof THEMES)[number], owner: string) => RGBA,
): string {
  const flat: Array<[string, unknown]> = [];
  for (const [path, pair] of colours) {
    flat.push([
      path,
      { $type: "color", $value: { light: hex8(pair.light), dark: hex8(pair.dark) } },
    ]);
  }
  for (const t of others) {
    let value: unknown = t.value;
    if (t.type === "typography") {
      value = { ...t.value, fontFamily: fontList(t.value.fontFamily, t.path) };
    } else if (t.type === "shadow") {
      const c = t.value.color ?? {};
      const light = sideToRGBA(c.light, "light", t.path);
      const dark = sideToRGBA(c.dark, "dark", t.path);
      value = { ...t.value, color: { light: hex8(light), dark: hex8(dark) } };
    }
    flat.push([t.path, { $type: t.type, $value: value }]);
  }
  flat.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const obj: Record<string, unknown> = { $generated: HEADER };
  for (const [path, v] of flat) obj[path] = v;
  return JSON.stringify(obj, null, 2) + "\n";
}

function slintOutput(leaves: Leaf[]): string {
  const lines: string[] = [];
  lines.push(`// ${HEADER}`);
  lines.push('import { Palette } from "std-widgets.slint";');
  lines.push("");
  lines.push("export enum ThemeChoice { light, dark, system }");
  lines.push("");
  lines.push("export global Tokens {");
  lines.push("    in-out property <ThemeChoice> theme: ThemeChoice.system;");
  lines.push(
    "    out property <bool> dark: theme == ThemeChoice.dark || (theme == ThemeChoice.system && Palette.color-scheme == ColorScheme.dark);",
  );
  lines.push("    in-out property <bool> reduced-motion: false;");
  lines.push("");
  for (const l of leaves) {
    // Colour names drop the leading "color" group.
    const segs = l.kind === "color" && l.path[0] === "color" ? l.path.slice(1) : l.path;
    const id = slintId(segs);
    switch (l.kind) {
      case "color":
        lines.push(
          `    out property <color> ${id}: dark ? ${hex8(l.value.dark)} : ${hex8(l.value.light)};`,
        );
        break;
      case "px":
        lines.push(`    out property <length> ${id}: ${fmt(l.value)}px;`);
        break;
      case "ms":
        lines.push(`    out property <duration> ${id}: reduced-motion ? 0ms : ${fmt(l.value)}ms;`);
        break;
      case "easing":
        lines.push(
          `    out property <easing> ${id}: cubic-bezier(${l.value.map(fmt).join(", ")});`,
        );
        break;
      case "font":
        lines.push(`    out property <string> ${id}: ${JSON.stringify(l.value.join(", "))};`);
        break;
      case "int":
        lines.push(`    out property <int> ${id}: ${l.value};`);
        break;
      case "shadow":
        break;
      default:
        fail(`internal: unknown leaf kind ${l.kind}`);
    }
  }
  lines.push("}");
  return lines.join("\n") + "\n";
}

function rgbaLiteral(c: RGBA): string {
  return `Rgba { r: ${c.r}, g: ${c.g}, b: ${c.b}, a: ${c.a} }`;
}

function rustOutput(leaves: Leaf[]): string {
  type Group = { plain: string[]; light: string[]; dark: string[] };
  const groups = new Map<string, Group>();
  const roles: string[] = [];
  const group = (name: string): Group => {
    let g = groups.get(name);
    if (!g) {
      g = { plain: [], light: [], dark: [] };
      groups.set(name, g);
    }
    return g;
  };

  for (const l of leaves) {
    const mod = rustMod(l.path[0]!);
    const rest = l.path.slice(1);
    const g = group(mod);
    switch (l.kind) {
      case "color": {
        const name = rustIdent(rest);
        g.light.push(`pub const ${name}: Rgba = ${rgbaLiteral(l.value.light)};`);
        g.dark.push(`pub const ${name}: Rgba = ${rgbaLiteral(l.value.dark)};`);
        if (l.path[0] === "color")
          roles.push(`    ("${l.path.join(".")}", color::light::${name}, color::dark::${name}),`);
        break;
      }
      case "px":
        g.plain.push(`pub const ${rustIdent(rest)}: f32 = ${fmtF32(l.value)};`);
        break;
      case "ms": {
        let name = rustIdent(rest);
        if (!name.endsWith("_MS")) name += "_MS";
        g.plain.push(`pub const ${name}: u32 = ${Math.round(l.value)};`);
        break;
      }
      case "easing":
        g.plain.push(
          `pub const ${rustIdent(rest)}: [f32; 4] = [${l.value.map(fmtF32).join(", ")}];`,
        );
        break;
      case "font":
        g.plain.push(`pub const ${rustIdent(rest)}: &str = ${JSON.stringify(l.value.join(", "))};`);
        break;
      case "int":
        g.plain.push(`pub const ${rustIdent(rest)}: u32 = ${l.value};`);
        break;
      case "shadow":
        break;
      default:
        fail(`internal: unknown leaf kind ${l.kind}`);
    }
  }

  const out: string[] = [];
  out.push(`// ${HEADER}`);
  out.push("");
  out.push("/// An 8-bit sRGB colour with alpha.");
  out.push("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
  out.push("pub struct Rgba {");
  out.push("    pub r: u8,");
  out.push("    pub g: u8,");
  out.push("    pub b: u8,");
  out.push("    pub a: u8,");
  out.push("}");
  out.push("");
  out.push("/// Design tokens, grouped by top-level `tokens.json` group.");
  out.push("pub mod tokens {");
  out.push("    use crate::generated::Rgba;");
  out.push("");
  const indent = (lines: string[], n: number): string[] => lines.map((l) => " ".repeat(n) + l);
  for (const [name, g] of groups) {
    if (g.light.length > 0) {
      out.push(`    pub mod ${name} {`);
      out.push("        pub mod light {");
      out.push("            use crate::generated::Rgba;");
      out.push(...indent(g.light, 12));
      out.push("        }");
      out.push("        pub mod dark {");
      out.push("            use crate::generated::Rgba;");
      out.push(...indent(g.dark, 12));
      out.push("        }");
      out.push(...indent(g.plain, 8));
      out.push("    }");
    } else if (g.plain.length > 0) {
      out.push(`    pub mod ${name} {`);
      out.push(...indent(g.plain, 8));
      out.push("    }");
    }
    out.push("");
  }
  out.push("    /// Colour roles: (dotted path, light, dark).");
  out.push("    pub const ROLES: &[(&str, Rgba, Rgba)] = &[");
  out.push(...roles);
  out.push("    ];");
  out.push("}");
  return out.join("\n") + "\n";
}

function contrastOutput(checks: Check[]): string {
  const count = (s: Check["status"]): number => checks.filter((c) => c.status === s).length;
  const lines: string[] = [];
  lines.push(`<!-- ${HEADER} -->`);
  lines.push(
    `Summary: ${checks.length} checks, ${count("PASS")} PASS, ${count("FAIL")} FAIL, ${count("EXEMPT")} EXEMPT.`,
  );
  lines.push("");
  lines.push("| Pair | Theme | Ratio | Min | Result |");
  lines.push("|---|---|---|---|---|");
  for (const c of checks) {
    lines.push(`| ${c.label} | ${c.theme} | ${c.ratio.toFixed(2)} | ${fmt(c.min)} | ${c.status} |`);
  }
  return lines.join("\n") + "\n";
}

