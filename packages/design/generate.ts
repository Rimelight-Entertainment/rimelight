export function generate(sourceText: string, sourceLabel: string = "tokens.json"): Output {
  let root: any;
  try {
    root = JSON.parse(sourceText);
  } catch (e) {
    fail(`${sourceLabel}: invalid JSON: ${(e as Error).message}`);
  }

  const tokens: Token[] = [];
  collect(root, [], undefined, tokens);
  const byPath = new Map<string, Token>(tokens.map((t) => [t.path, t]));

  // --- shades -------------------------------------------------------------
  const shades = new Map<string, number[]>();
  for (const t of tokens) {
    if (t.type !== "rimelight.shade") continue;
    const m = /^shades\.(\d+)$/.exec(t.path);
    if (!m) fail(`${t.path}: shades must be named shades.<number>`);
    if (m[1] === "0" || m[1] === "1000")
      fail(`${t.path}: shades 0 and 1000 are fixed (white and black) and must not be defined`);
    const v = t.value;
    if (!Array.isArray(v) || v.length !== 4 || v.some((x) => typeof x !== "number")) {
      fail(`${t.path}: shade must be [lightL, lightChromaFactor, darkL, darkChromaFactor]`);
    }
    shades.set(m[1]!, v);
  }
  if (shades.size === 0) fail("no shades defined (expected shades.<50..950>)");
  const shadeOrder = ["0", ...[...shades.keys()].sort((a, b) => Number(a) - Number(b)), "1000"];

  // raw: path -> per-theme side (hex/ref string, or an already-final RGBA)
  const raw = new Map<string, { light: string | RGBA; dark: string | RGBA }>();

  // --- ramps --------------------------------------------------------------
  const ramps: string[] = [];
  for (const t of tokens) {
    if (t.type !== "rimelight.ramp") continue;
    const segs = t.path.split(".");
    if (segs.length !== 2 || segs[0] !== "ramp")
      fail(`${t.path}: ramps must be named ramp.<palette>`);
    const palette = segs[1];
    const { chroma, hue } = t.value ?? {};
    if (typeof chroma !== "number" || typeof hue !== "number")
      fail(`${t.path}: ramp $value must be {chroma, hue}`);
    ramps.push(palette!);

    const pins: Record<string, Partial<Record<string, string>>> = t.ext?.pin ?? {};
    for (const s of Object.keys(pins)) {
      if (!shadeOrder.includes(s)) fail(`${t.path}: pin for unknown shade ${s}`);
      if (s === "0" || s === "1000")
        fail(`${t.path}: shades 0 and 1000 are fixed and cannot be pinned`);
    }

    for (const s of shadeOrder) {
      let pair: { light: RGBA; dark: RGBA };
      if (s === "0") pair = { light: WHITE, dark: WHITE };
      else if (s === "1000") pair = { light: BLACK, dark: BLACK };
      else {
        const sh = shades.get(s) as number[];
        const make = (L: number, factor: number): RGBA => {
          const [r, g, b] = gamutMapOklch(L, factor * chroma, hue);
          return { r: toByte(r!), g: toByte(g!), b: toByte(b!), a: 255 };
        };
        pair = { light: make(sh[0]!, sh[1]!), dark: make(sh[2]!, sh[3]!) };
      }
      const pin = pins[s];
      if (pin) {
        for (const theme of THEMES) {
          if (pin[theme] !== undefined)
            pair[theme] = parseHex(String(pin[theme]), `${t.path}.pin.${s}.${theme}`);
        }
      }
      raw.set(`ramp.${palette}.${s}`, pair);
    }
  }

  const rampColour = (palette: string, shade: string, theme: (typeof THEMES)[number]): RGBA => {
    const entry = raw.get(`ramp.${palette}.${shade}`);
    if (!entry)
      fail(`ramp.${palette}: shade ${shade} is needed for the palette roles but is not in shades`);
    return entry[theme] as RGBA;
  };

  // --- explicit colour tokens ----------------------------------------------
  for (const t of tokens) {
    if (t.type !== "color") continue;
    const v = t.value;
    if (!v || typeof v !== "object" || typeof v.light !== "string" || typeof v.dark !== "string") {
      fail(
        `${t.path}: colour $value must be {"light": ..., "dark": ...} with hex or reference strings`,
      );
    }
    raw.set(t.path, { light: v.light, dark: v.dark });
  }

  // --- generated per-palette roles (D5), unless overridden -----------------
  // The shade curve already flips lightness in dark mode (dark 600 is lighter than dark 500), so each role uses the
  // same shade name in both themes. Solid fills carry text, so they sit at 600, where on-accent text reaches 4.5:1.
  for (const p of ramps) {
    const generated: Array<[string, { light: RGBA; dark: RGBA }]> = [
      ["solid", { light: rampColour(p, "600", "light"), dark: rampColour(p, "600", "dark") }],
      ["solid-hover", { light: rampColour(p, "700", "light"), dark: rampColour(p, "700", "dark") }],
      ["text", { light: rampColour(p, "600", "light"), dark: rampColour(p, "700", "dark") }],
      ["soft", { light: rampColour(p, "100", "light"), dark: rampColour(p, "100", "dark") }],
      ["border", { light: rampColour(p, "500", "light"), dark: rampColour(p, "500", "dark") }],
    ];
    for (const [name, pair] of generated) {
      const path = `color.palette.${p}.${name}`;
      if (!raw.has(path)) raw.set(path, { light: pair.light, dark: pair.dark });
    }
  }

  // --- reference resolution -------------------------------------------------
  const memo = new Map<string, RGBA>();

  function resolveRef(
    path: string,
    theme: (typeof THEMES)[number],
    stack: string[],
    from: string,
  ): RGBA {
    const key = `${path}@${theme}`;
    const hit = memo.get(key);
    if (hit) return hit;
    if (stack.includes(key)) fail(`reference cycle: ${[...stack, key].join(" -> ")}`);
    const entry = raw.get(path);
    if (!entry) fail(`${from}: reference {${path}} does not name a colour token`);
    const side = entry[theme];
    let c: RGBA;
    if (typeof side === "string") {
      const m = /^\{(.+)\}$/.exec(side);
      c = m ? resolveRef(m[1]!, theme, [...stack, key], path) : parseHex(side, `${path}.${theme}`);
    } else {
      c = side;
    }
    memo.set(key, c);
    return c;
  }

  function sideToRGBA(side: unknown, theme: (typeof THEMES)[number], owner: string): RGBA {
    if (typeof side !== "string") fail(`${owner}.${theme}: colour side must be a string`);
    const m = /^\{(.+)\}$/.exec(side);
    return m ? resolveRef(m[1]!, theme, [], owner) : parseHex(side, `${owner}.${theme}`);
  }

  const colours = new Map<string, Pair>();
  for (const path of raw.keys()) {
    colours.set(path, {
      light: resolveRef(path, "light", [], path),
      dark: resolveRef(path, "dark", [], path),
    });
  }

  // --- other token types ----------------------------------------------------
  const others = tokens.filter(
    (t) => t.type !== "color" && t.type !== "rimelight.ramp" && t.type !== "rimelight.shade",
  );

  function fontList(v: unknown, where: string): string[] {
    if (typeof v === "string") {
      const m = /^\{(.+)\}$/.exec(v);
      if (m) {
        const target = byPath.get(m[1]!);
        if (!target || target.type !== "fontFamily")
          fail(`${where}: reference {${m[1]}} is not a fontFamily token`);
        return fontList(target.value, m[1]!);
      }
      return [v];
    }
    if (Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === "string"))
      return v as string[];
    fail(`${where}: fontFamily must be a string or a list of strings`);
  }

  // Leaves: every emitted value, flattened. Path segments are kebab-case.
  type Leaf = { kind: string; path: string[]; value: any };
  const leaves: Leaf[] = [];

  for (const p of ramps) {
    for (const s of shadeOrder) {
      leaves.push({ kind: "color", path: ["ramp", p, s], value: colours.get(`ramp.${p}.${s}`) });
    }
  }
  for (const [path, pair] of colours) {
    if (path.startsWith("ramp.")) continue;
    leaves.push({ kind: "color", path: path.split(".").map(kebab), value: pair });
  }

  for (const t of others) {
    const base = t.path.split(".").map(kebab);
    switch (t.type) {
      case "dimension":
        leaves.push({ kind: "px", path: base, value: parseDimension(t.value, t.path) });
        break;
      case "duration":
        leaves.push({ kind: "ms", path: base, value: parseDuration(t.value, t.path) });
        break;
      case "cubicBezier": {
        const v = t.value;
        if (!Array.isArray(v) || v.length !== 4 || v.some((x) => typeof x !== "number")) {
          fail(`${t.path}: cubicBezier must be [x1, y1, x2, y2]`);
        }
        leaves.push({ kind: "easing", path: base, value: v });
        break;
      }
      case "fontFamily":
        leaves.push({ kind: "font", path: base, value: fontList(t.value, t.path) });
        break;
      case "typography":
        for (const key of Object.keys(t.value ?? {})) {
          const sub = t.value[key];
          const path = [...base, kebab(key)];
          const where = `${t.path}.${key}`;
          if (key === "fontFamily")
            leaves.push({ kind: "font", path, value: fontList(sub, where) });
          else if (key === "fontWeight") {
            if (typeof sub !== "number") fail(`${where}: fontWeight must be a number`);
            leaves.push({ kind: "int", path, value: sub });
          } else leaves.push({ kind: "px", path, value: parseDimension(sub, where) });
        }
        break;
      case "shadow": {
        const v = t.value ?? {};
        const ox = parseDimension(v.offsetX, `${t.path}.offsetX`);
        const oy = parseDimension(v.offsetY, `${t.path}.offsetY`);
        const blur = parseDimension(v.blur, `${t.path}.blur`);
        const spread = parseDimension(v.spread, `${t.path}.spread`);
        const color: Pair = {
          light: sideToRGBA(v.color?.light, "light", t.path),
          dark: sideToRGBA(v.color?.dark, "dark", t.path),
        };
        leaves.push({ kind: "px", path: [...base, "offset-x"], value: ox });
        leaves.push({ kind: "px", path: [...base, "offset-y"], value: oy });
        leaves.push({ kind: "px", path: [...base, "blur"], value: blur });
        leaves.push({ kind: "px", path: [...base, "spread"], value: spread });
        leaves.push({ kind: "color", path: [...base, "color"], value: color });
        leaves.push({
          kind: "shadow",
          path: base,
          value: { offsetX: ox, offsetY: oy, blur, spread, color },
        });
        break;
      }
      case "number":
        if (typeof t.value !== "number" || !Number.isInteger(t.value))
          fail(`${t.path}: number must be an integer`);
        leaves.push({ kind: "int", path: base, value: t.value });
        break;
      default:
        fail(`${t.path}: unsupported $type "${t.type}"`);
    }
  }

  // --- contrast -------------------------------------------------------------
  const cfg = root.$extensions?.rimelight?.contrast ?? {};
  const exempt = new Set<string>((cfg.exempt ?? []).map((e: { role: string }) => e.role));
  type Def = { label: string; fg: string; bg: string; min: number };
  const defs: Def[] = (cfg.pairs ?? []).map((p: { fg: string; bg: string; min?: number }) => ({
    label: `${p.fg} on ${p.bg}`,
    fg: p.fg,
    bg: p.bg,
    min: p.min ?? DEFAULT_MIN,
  }));
  if (cfg.paletteChecks === true) {
    for (const p of ramps) {
      const solid = `color.palette.${p}.solid`;
      const text = `color.palette.${p}.text`;
      const soft = `color.palette.${p}.soft`;
      defs.push({
        label: `[${p}] text.on-accent on solid`,
        fg: "color.text.on-accent",
        bg: solid,
        min: 4.5,
      });
      defs.push({
        label: `[${p}] text on surface.base`,
        fg: text,
        bg: "color.surface.base",
        min: 4.5,
      });
      defs.push({
        label: `[${p}] text on surface.raised`,
        fg: text,
        bg: "color.surface.raised",
        min: 4.5,
      });
      defs.push({
        label: `[${p}] solid on surface.base`,
        fg: solid,
        bg: "color.surface.base",
        min: 3.0,
      });
      defs.push({ label: `[${p}] text on soft`, fg: text, bg: soft, min: 4.5 });
    }
  }

  const checks: Check[] = [];
  for (const d of defs) {
    const fgPair =
      colours.get(d.fg) ?? fail(`contrast pair "${d.label}": ${d.fg} is not a colour token`);
    const bgPair =
      colours.get(d.bg) ?? fail(`contrast pair "${d.label}": ${d.bg} is not a colour token`);
    for (const theme of THEMES) {
      const base = theme === "light" ? WHITE : BLACK;
      const bgRaw = bgPair[theme];
      const bgOpaque = bgRaw.a === 255 ? bgRaw : over(bgRaw, base);
      const fgOpaque = over(fgPair[theme], bgOpaque);
      const ratio = contrastRatio(fgOpaque, bgOpaque);
      let status: Check["status"];
      if (ratio >= d.min) status = "PASS";
      else if (exempt.has(d.fg)) status = "EXEMPT";
      else status = "FAIL";
      checks.push({ label: d.label, theme, ratio, min: d.min, status });
    }
  }

  // --- outputs --------------------------------------------------------------
  const files = new Map<string, string>();
  files.set("generated/tokens.css", cssOutput(leaves, ramps, shadeOrder));
  files.set("generated/tokens.json", jsonOutput(colours, others, fontList, sideToRGBA));
  files.set("crate/ui/tokens.slint", slintOutput(leaves));
  files.set("crate/src/generated.rs", rustOutput(leaves));
  files.set("generated/contrast.md", contrastOutput(checks));
  return { files, checks };
}

