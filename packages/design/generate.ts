const HERE = dirname(fileURLToPath(import.meta.url));
const HEADER = "generated by packages/design/generate.ts from tokens.json, do not edit";
const DEFAULT_MIN = 4.5;
const GAMUT_EPS = 1e-6;
const CHROMA_STEP = 0.0001;
const THEMES = ["light", "dark"] as const;

export interface RGBA {
  r: number;
  g: number;
  b: number;
  a: number;
}

export interface Pair {
  light: RGBA;
  dark: RGBA;
}

export interface Check {
  label: string;
  theme: string;
  ratio: number;
  min: number;
  status: "PASS" | "FAIL" | "EXEMPT";
}

export interface Output {
  files: Map<string, string>;
  checks: Check[];
}

export class GenError extends Error {}

function fail(message: string): never {
  throw new GenError(message);
}

const WHITE: RGBA = { r: 255, g: 255, b: 255, a: 255 };
const BLACK: RGBA = { r: 0, g: 0, b: 0, a: 255 };

// ---------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------

const kebab = (s: string): string => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

function fmt(n: number): string {
  return Number.isInteger(n) ? String(n) : String(Number(n.toFixed(6)));
}

function fmtF32(n: number): string {
  return Number.isInteger(n) ? `${n}.0` : fmt(n);
}

function toByte(v: number): number {
  return Math.round(Math.min(1, Math.max(0, v)) * 255);
}

function hex8(c: RGBA): string {
  const p = (n: number): string => n.toString(16).toUpperCase().padStart(2, "0");
  return `#${p(c.r)}${p(c.g)}${p(c.b)}${c.a === 255 ? "" : p(c.a)}`;
}

const HEX_RE = /^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$/;

function parseHex(s: string, where: string): RGBA {
  const m = HEX_RE.exec(s);
  if (!m) fail(`${where}: "${s}" is not a #RRGGBB or #RRGGBBAA colour`);
  const n = parseInt(m[1]!, 16);
  return {
    r: (n >> 16) & 255,
    g: (n >> 8) & 255,
    b: n & 255,
    a: m[2] ? parseInt(m[2], 16) : 255,
  };
}

function parseDimension(v: unknown, where: string): number {
  const m = typeof v === "string" ? /^(-?\d+(?:\.\d+)?)px$/.exec(v) : null;
  if (!m)
    fail(`${where}: dimension must be a pixel value such as "34px", got ${JSON.stringify(v)}`);
  return Number(m[1]);
}

function parseDuration(v: unknown, where: string): number {
  const m = typeof v === "string" ? /^(-?\d+(?:\.\d+)?)(ms|s)$/.exec(v) : null;
  if (!m) fail(`${where}: duration must be "<n>ms" or "<n>s", got ${JSON.stringify(v)}`);
  return m[2] === "s" ? Number(m[1]) * 1000 : Number(m[1]);
}

// ---------------------------------------------------------------------------
// OKLCH -> sRGB (Bjorn Ottosson's matrices) with gamut mapping
// ---------------------------------------------------------------------------

function gammaEncode(x: number): number {
  if (x <= 0.0031308) return 12.92 * x;
  return 1.055 * Math.pow(x, 1 / 2.4) - 0.055;
}

// Returns gamma-encoded sRGB channels in [0,1] when in gamut; may be outside otherwise.
function oklchToSrgbUnclamped(L: number, C: number, hDeg: number): number[] {
  const h = (hDeg * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const lp = L + 0.3963377774 * a + 0.2158037573 * b;
  const mp = L - 0.1055613458 * a - 0.0638541728 * b;
  const sp = L - 0.0894841775 * a - 1.291485548 * b;
  const l = lp * lp * lp;
  const m = mp * mp * mp;
  const s = sp * sp * sp;
  const r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
  const g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
  const bl = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s;
  return [gammaEncode(r), gammaEncode(g), gammaEncode(bl)];
}

function inGamut(c: number[]): boolean {
  return c.every((v) => v >= -GAMUT_EPS && v <= 1 + GAMUT_EPS);
}

// Keeps L and hue; binary-searches the chroma down until the colour fits sRGB.
export function gamutMapOklch(L: number, C: number, hDeg: number): number[] {
  const direct = oklchToSrgbUnclamped(L, C, hDeg);
  if (inGamut(direct)) return direct.map((v) => Math.min(1, Math.max(0, v)));
  let lo = 0;
  let hi = C;
  while (hi - lo > CHROMA_STEP) {
    const mid = (lo + hi) / 2;
    if (inGamut(oklchToSrgbUnclamped(L, mid, hDeg))) lo = mid;
    else hi = mid;
  }
  return oklchToSrgbUnclamped(L, lo, hDeg).map((v) => Math.min(1, Math.max(0, v)));
}

// ---------------------------------------------------------------------------
// WCAG 2 contrast
// ---------------------------------------------------------------------------

function luminance(c: RGBA): number {
  const lin = (v: number): number => {
    const x = v / 255;
    return x <= 0.03928 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * lin(c.r) + 0.7152 * lin(c.g) + 0.0722 * lin(c.b);
}

// Composites `top` over `under`; the result is opaque.
function over(top: RGBA, under: RGBA): RGBA {
  const a = top.a / 255;
  const mix = (t: number, u: number): number => Math.round(t * a + u * (1 - a));
  return { r: mix(top.r, under.r), g: mix(top.g, under.g), b: mix(top.b, under.b), a: 255 };
}

function contrastRatio(x: RGBA, y: RGBA): number {
  const l1 = luminance(x);
  const l2 = luminance(y);
  const hi = Math.max(l1, l2);
  const lo = Math.min(l1, l2);
  return (hi + 0.05) / (lo + 0.05);
}

// ---------------------------------------------------------------------------
// Token collection
// ---------------------------------------------------------------------------

interface Token {
  path: string;
  type: string;
  value: any;
  ext: any;
}

function collect(node: any, path: string[], inheritedType: string | undefined, out: Token[]): void {
  if (node === null || typeof node !== "object" || Array.isArray(node)) return;
  if ("$value" in node) {
    out.push({
      path: path.join("."),
      type: node.$type ?? inheritedType ?? "",
      value: node.$value,
      ext: node.$extensions?.rimelight,
    });
    return;
  }
  const groupType: string | undefined = node.$type ?? inheritedType;
  for (const key of Object.keys(node)) {
    if (key.startsWith("$")) continue;
    collect(node[key], [...path, key], groupType, out);
  }
}

